import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const app=read('./edge-syllabus-app-common.ts');
const web=read('./edge-syllabus-web-common.ts');
const pub=read('./edge-publish-syllabus-app-secure.ts');
let passed=0;const check=(name,fn)=>{fn();passed++;console.log(`PASS ${passed}: ${name}`)};
check('common asset server contains no Supabase service role',()=>assert.ok(!app.includes('SUPABASE_SERVICE_ROLE_KEY')));
check('common asset server contains no branch_id authority',()=>assert.ok(!app.includes('branch_id')));
check('common asset server blocks nested repository paths',()=>assert.ok(app.includes('p.includes("/")')));
check('common asset server uses no-store',()=>assert.ok(app.includes('no-store')));
check('web launcher removes Khalsa title',()=>assert.ok(!web.includes('Khalsa CBSE')));
check('web launcher is generic Sri Chaitanya tracker',()=>assert.ok(web.includes('Sri Chaitanya School | Syllabus Tracker')));
check('web launcher contains no branch_id authority',()=>assert.ok(!web.includes('branch_id')));
check('publisher requires POST',()=>assert.ok(pub.includes('req.method!=="POST"')));
check('publisher requires server managed secret',()=>assert.ok(pub.includes('SYLLABUS_PUBLISH_SECRET')));
check('publisher uses x-publish-key',()=>assert.ok(pub.includes('x-publish-key')));
check('publisher requires exact 40 char commit',()=>assert.ok(pub.includes('/^[0-9a-f]{40}$/')));
check('publisher pins raw GitHub fetch to supplied commit',()=>assert.ok(pub.includes('${commit}/')));
check('publisher writes publication marker',()=>assert.ok(pub.includes('publication.json')));
check('publisher does not authorize branch roles',()=>assert.ok(!/Super Admin|Principal|HOD|Teacher/.test(pub)));
check('publisher has fixed file allowlist',()=>assert.ok(pub.includes('const FILES:Record<string,string>=')));
console.log(`TOTAL ${passed}/${passed} PASSED`);
